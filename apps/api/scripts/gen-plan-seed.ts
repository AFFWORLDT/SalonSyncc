import { PLAN_DEFAULTS } from "../../../packages/features/src/index.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const sortOrder = ["free", "pro", "pro_max"] as const;

const out: string[] = ["-- GENERATED by scripts/gen-plan-seed.ts from PLAN_DEFAULTS. Do not edit."];
sortOrder.forEach((id, i) => {
  const p = PLAN_DEFAULTS[id];
  out.push(
    `INSERT INTO plans(id,name,price_monthly,currency,limits_json,active,sort) VALUES(${q(id)},${q(p.name)},${p.priceMonthly},${q(p.currency)},${q(JSON.stringify(p.limits))},1,${i + 1});`,
  );
});
for (const id of sortOrder) {
  for (const f of PLAN_DEFAULTS[id].features) {
    out.push(`INSERT INTO plan_features(plan_id,feature_key) VALUES(${q(id)},${q(f)});`);
  }
}
console.log(out.join("\n"));
